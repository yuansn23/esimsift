def to_row(brand, o):
    return {
        "brand": brand, "brand_name": BRANDS[brand]["brand_name"],
        "code": o["code"] or "", "kind": o["kind"], "discount": o["discount"] or "",
        "percent": "" if o["percent"] is None else o["percent"],
        "amount": "" if o["amount"] is None else o["amount"],
        "currency": o["currency"] or "", "audience": o["audience"] or "",
        "where": o["where"] or "", "min_spend": o["min_spend"] or "",
        "max_discount": o["max_discount"] or "", "stackable": o["stackable"] or "",
        "uses": o["uses"] or "", "scope": o["scope"] or "",
        "expires": o["expires"] or "", "source": o["source"] or "",
        "source_url": o["source_url"] or "", "verified": o["verified"] or "",
        "confidence": o["confidence"] or "",
        "terms": " | ".join(o["terms"]) if o["terms"] else "",
    }


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for brand, data in BRANDS.items():
        offs = data["offers"]
        data["offer_count"] = len(offs)
        with open(os.path.join(OUT, brand + ".json"), "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        for o in offs:
            rows.append(to_row(brand, o))

    # combined json
    with open(os.path.join(OUT, "promos.json"), "w", encoding="utf-8") as f:
        json.dump({"captured": CAPTURED, "brand_count": len(BRANDS),
                   "offer_count": len(rows), "brands": BRANDS}, f,
                  ensure_ascii=False, indent=1)

    # csv
    cols = ["brand", "brand_name", "code", "kind", "discount", "percent", "amount",
            "currency", "audience", "where", "min_spend", "max_discount", "stackable",
            "uses", "scope", "expires", "source", "source_url", "verified",
            "confidence", "terms"]
    with open(os.path.join(OUT, "promos_all.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for r in rows:
            w.writerow(r)

    print("brands=%d  offers=%d" % (len(BRANDS), len(rows)))
    for b, d in BRANDS.items():
        kinds = {}
        for o in d["offers"]:
            kinds[o["kind"]] = kinds.get(o["kind"], 0) + 1
        print("  %-10s offers=%-3d %s" % (b, len(d["offers"]), kinds))


if __name__ == "__main__":
    main()
