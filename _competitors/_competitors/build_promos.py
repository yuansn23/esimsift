"""
eSIM competitor promo/discount codes — structured dataset builder.

Emits (into _competitors/promos/):
  <brand>.json      one file per brand: offers[] + referral + loyalty + notes
  promos_all.csv    flat table, one row per offer
  promos.json       all brands in one object

Schema per offer:
  code         str|""        coupon/promo code ("" for pure referral/loyalty, no typed code)
  kind         str           coupon | referral | loyalty | card_benefit | student | free_trial | bonus_data | cashback
  discount     str           human headline, e.g. "15% off", "$5 off", "+6 GB", "€2/day"
  percent      float|None    numeric % when it is a straight percentage
  amount       float|None    fixed amount when not a percentage
  currency     str|""        currency of `amount`
  audience     str           new | existing | all | students | cardholders | invited_friend
  where        str           web+app | app | web
  min_spend    str|""        minimum spend if any
  max_discount str|""        cap if any
  stackable    str           no | yes | one_per_order | unknown
  uses         str           once_per_account | unlimited | unknown | ...
  scope        str           what it applies to (all plans, unlimited only, ...)
  expires      str|""        date or "ongoing"/"unknown"
  terms        list[str]     extra rule lines
  source       str           official | aggregator
  source_url   str
  verified     str           date string or ""
  confidence   str           official | verified-thirdparty | reported
"""

